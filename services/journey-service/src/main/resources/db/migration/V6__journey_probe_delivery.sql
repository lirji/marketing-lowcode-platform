CREATE TABLE mk_journey_probe_delivery (
    tenant_id VARCHAR(64) NOT NULL COMMENT '已登记挑战的可信租户编号',
    environment_name VARCHAR(32) NOT NULL COMMENT '执行环境；按本站配置领取',
    cell_id VARCHAR(64) NOT NULL COMMENT '执行区域；按本站配置领取',
    namespace_name VARCHAR(128) NOT NULL COMMENT 'Journey命名空间；按本站配置领取',
    campaign_id VARCHAR(64) NOT NULL COMMENT '活动编号；不跨活动复用进度',
    probe_id VARCHAR(64) NOT NULL COMMENT '不可变签名挑战编号；同挑战只创建一个投递任务',
    destination_topic VARCHAR(249) NOT NULL COMMENT '首次排队时的可信Kafka目标topic，不能由请求指定',
    total_routes INT NOT NULL COMMENT '固定路由总数；16乘实际并行度，最大2048',
    next_nonce INT NOT NULL COMMENT '下一未确认批次的起始nonce；未知发送结果不得推进',
    delivery_state VARCHAR(16) NOT NULL COMMENT '显式code：QUEUED/RETRY/SENT/DEAD/EXPIRED/COVERED；SENT不代表Flink覆盖',
    pending BOOLEAN GENERATED ALWAYS AS (delivery_state IN ('QUEUED','RETRY')) STORED COMMENT '派生待执行标记，用于有序领取索引；不是第二套权威状态',
    failure_count INT NOT NULL COMMENT '连续失败次数；成功批次重置，达到上限转DEAD',
    next_attempt_at VARCHAR(40) NOT NULL COMMENT '下一次允许领取的UTC九位小数时间',
    expires_at VARCHAR(40) NOT NULL COMMENT '原签名挑战到期时间；不可续期',
    lease_owner VARCHAR(64) NULL COMMENT '当前领取者不可猜测标识；终态或释放后为空',
    lease_epoch BIGINT NOT NULL COMMENT '单调租约代次；隔离旧执行者的迟到状态写入',
    lease_until VARCHAR(40) NULL COMMENT '当前租约到期UTC时间；未领取或释放后为空',
    last_error_code VARCHAR(96) NOT NULL COMMENT '最近稳定错误code；不保存内部异常或敏感信息',
    created_by VARCHAR(128) NOT NULL COMMENT '首次派发的可信调用者',
    created_at VARCHAR(40) NOT NULL COMMENT '首次排队时间；UTC九位小数',
    updated_at VARCHAR(40) NOT NULL COMMENT '最近进度更新时间；UTC九位小数',
    PRIMARY KEY (tenant_id, environment_name, cell_id, namespace_name, campaign_id, probe_id),
    KEY idx_probe_delivery_due (environment_name, cell_id, namespace_name, pending, next_attempt_at, created_at, lease_until),
    CONSTRAINT fk_probe_delivery_challenge FOREIGN KEY (tenant_id, environment_name, cell_id, namespace_name, campaign_id, probe_id)
        REFERENCES mk_journey_execution_probe (tenant_id, environment_name, cell_id, namespace_name, campaign_id, probe_id),
    CONSTRAINT ck_probe_delivery_routes CHECK (total_routes BETWEEN 1 AND 2048 AND next_nonce BETWEEN 0 AND total_routes),
    CONSTRAINT ck_probe_delivery_failures CHECK (failure_count >= 0 AND lease_epoch >= 0),
    CONSTRAINT ck_probe_delivery_state CHECK (delivery_state IN ('QUEUED','RETRY','SENT','DEAD','EXPIRED','COVERED'))
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin COMMENT '显式派发后的持久探针投递进度；无历史回填，无业务发布副作用';
