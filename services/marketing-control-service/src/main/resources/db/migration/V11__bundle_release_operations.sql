create table mk_bundle_release_operation (
  tenant_id varchar(64) not null comment '可信租户编号',
  operation_id varchar(64) not null comment '命令永久编号，同时作为运行授权编号',
  campaign_id varchar(64) not null comment '活动编号',
  environment_name varchar(32) not null comment '目标环境',
  cell_id varchar(64) not null comment '准入单元',
  bundle_id varchar(64) not null comment '已冻结组合编号',
  version_no bigint not null comment '目标组合版本',
  action_name varchar(16) not null comment 'ACTIVATE整体发布或ROLLBACK整体回滚',
  expected_sequence bigint not null comment '提交人观察到的实际应用序号，首次为零',
  activation_sequence bigint not null comment '本活动位置严格递增的授权序号，失败不回收',
  command_key varchar(128) character set ascii collate ascii_bin not null comment '当前租户内永久幂等键',
  requested_deadline varchar(40) null comment '定时命令指定的原始UTC截止时间，手工命令为空',
  apply_before varchar(40) not null comment '运行端最迟切换时点，不能晚于组合到期',
  created_by varchar(128) not null comment '创建命令的可信身份',
  state_name varchar(16) not null comment 'PENDING等候、APPLIED已确认、EXPIRED过期或REJECTED拒绝',
  reason_code varchar(96) null comment '最近一次推进的稳定原因码',
  directive_json mediumtext null comment '经过审批和就绪门禁后签发的不可变授权，未知结果必须重用',
  created_at varchar(40) not null comment 'UTC提交时刻',
  updated_at varchar(40) not null comment 'UTC最近一次状态确认时刻',
  primary key (tenant_id, operation_id),
  unique key uk_bundle_operation_key (tenant_id,command_key),
  unique key uk_bundle_operation_sequence (tenant_id,campaign_id,environment_name,cell_id,activation_sequence),
  key idx_bundle_operation_applied (tenant_id,campaign_id,environment_name,cell_id,state_name,activation_sequence),
  key idx_bundle_operation_history (tenant_id,bundle_id,state_name),
  constraint fk_bundle_operation_bundle foreign key (tenant_id,bundle_id) references mk_release_bundle(tenant_id,bundle_id),
  constraint ck_bundle_operation_sequence check (activation_sequence > expected_sequence and expected_sequence >= 0),
  constraint ck_bundle_operation_state check (state_name in ('PENDING','APPLIED','EXPIRED','REJECTED'))
) comment '活动整体发布命令与Decision应用回执投影，投影只有确认同一签名授权实际提交后才更新';
