CREATE TABLE mk_release_operation_audit (
    event_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '审计事件游标',
    tenant_id VARCHAR(64) NOT NULL COMMENT '已认证租户',
    attempt_id VARCHAR(36) NULL COMMENT '一次入口尝试的内部标识，独立查证回执时为空',
    actor_id VARCHAR(128) NOT NULL COMMENT '可信操作人或查证人',
    trace_id VARCHAR(64) NULL COMMENT '验证过格式的链路编号',
    action_code VARCHAR(32) NOT NULL COMMENT '稳定操作码，区分发布、回滚、排期暂停和恢复',
    stage_code VARCHAR(32) NOT NULL COMMENT '尝试、受理、确认、拒绝、重放等观测阶段',
    campaign_id VARCHAR(64) NULL COMMENT '已核实可访问的活动内部编号',
    organization_id VARCHAR(64) NULL COMMENT '活动归属组织',
    shop_id VARCHAR(64) NULL COMMENT '活动归属店铺',
    resource_id VARCHAR(64) NULL COMMENT '原发布操作或排期编号',
    business_no VARCHAR(64) NULL COMMENT '原发布操作或排期的可读业务编号',
    version_no BIGINT NULL COMMENT '已核实的目标发布版本',
    activation_sequence BIGINT NULL COMMENT '运行端校验的单调发布序号',
    before_state VARCHAR(24) NULL COMMENT '本次事务读取的前置状态',
    after_state VARCHAR(24) NULL COMMENT '控制面状态或已核实的运行终态',
    reason_code VARCHAR(96) NULL COMMENT '稳定原因码，不保存错误原文',
    chain_audit_id VARCHAR(64) NULL COMMENT '此次受理或终态在原营销审计链上的节点',
    original_event_id BIGINT NULL COMMENT '重复调用引用的原受理或原终态事件',
    observed_at VARCHAR(40) NULL COMMENT '已校验运行回执报告的实际生效时点',
    recorded_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '数据库记录时间，统一采用 UTC 连接配置',
    PRIMARY KEY (event_id),
    UNIQUE KEY uk_release_audit_chain (tenant_id, chain_audit_id),
    KEY ix_release_audit_campaign (tenant_id, campaign_id, event_id),
    KEY ix_release_audit_origin (tenant_id, resource_id, stage_code, event_id),
    KEY ix_release_audit_attempt (tenant_id, attempt_id, event_id)
) COMMENT '营销发布入口尝试、原控制面审计链及已经核实的运行结果';
