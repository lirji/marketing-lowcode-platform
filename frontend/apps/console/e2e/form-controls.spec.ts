import { expect, test } from '@playwright/test'

test('custom selects filter visible records and preserve the containing form on Escape', async ({ page }, testInfo) => {
  await page.goto('/campaigns')
  const status = page.getByRole('combobox', { name: '状态筛选' })
  await status.click()
  const options = page.getByRole('listbox')
  await expect(options).toBeVisible()
  const box = await options.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.screenshot({ path: testInfo.outputPath('status-select.png') })
  await page.getByRole('option', { name: '草稿', exact: true }).click()
  await expect(status).toHaveText('草稿')
  await expect(page).toHaveURL(/status=DRAFT/)
  await page.getByRole('button', { name: '创建活动', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '创建营销活动' })
  await expect(modal.getByRole('textbox', { name: '活动名称', exact: true })).toHaveAccessibleDescription(/2–80/)
  const intent = modal.getByRole('combobox', { name: /创建后进入/ })
  await intent.click()
  await page.getByRole('option', { name: '邀请有礼 · 裂变规则设计器', exact: true }).click()
  await expect(modal).toBeVisible()
  await expect(intent).toContainText('邀请有礼')
  await intent.click()
  await page.getByRole('option', { name: '邀请有礼 · 裂变规则设计器', exact: true }).press('Escape')
  await expect(modal).toBeVisible()
  await expect(intent).toBeFocused()
  await page.screenshot({ path: testInfo.outputPath('form-tips.png') })
  await modal.getByRole('button', { name: '取消', exact: true }).click()
  await expect(status).toHaveText('草稿')
})

test('calendar selects time without typing ISO and cancel keeps the existing draft', async ({ page }, testInfo) => {
  await page.goto('/designers/referral')
  const trigger = page.getByRole('button', { name: '开始时间', exact: true })
  await trigger.click()
  const picker = page.getByRole('dialog', { name: '选择开始时间' })
  await expect(picker).toContainText('北京时间 UTC+08:00')
  await expect(picker.getByRole('textbox')).toHaveCount(0)
  await expect(picker.getByRole('button', { name: '确认时间' })).toBeDisabled()
  await picker.locator('.rdp-day_button').first().click()
  await picker.getByRole('combobox', { name: '开始时间·时' }).click()
  await page.getByRole('option', { name: '09', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('date-time-picker.png') })
  const box = await picker.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  expect(box!.y).toBeGreaterThanOrEqual(0)
  expect(box!.y + box!.height).toBeLessThanOrEqual(page.viewportSize()!.height)
  await picker.getByRole('button', { name: '确认时间' }).click()
  await expect(trigger).toContainText('09:00:00')
  const before = await trigger.textContent() ?? ''
  await trigger.click()
  await picker.getByRole('combobox', { name: '开始时间·时' }).click()
  await page.getByRole('option', { name: '10', exact: true }).click()
  await picker.getByRole('button', { name: '取消', exact: true }).click()
  await expect(trigger).toHaveText(before)
  await expect(trigger).toBeFocused()
  await expect(page.getByRole('button', { name: '绑定时间', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '仿真当前时间', exact: true })).toBeVisible()
})

test('search matches formatted list dates, IDs and Chinese status labels', async ({ page }) => {
  await page.addInitScript(() => { window.__MARKETING_CONFIG__ = { API_BASE_URL: '', DEMO_MODE: false, AUTH_MODE: 'DEV', ALLOW_DEV_AUTH: true } })
  await page.route('**/api/v1/**', (route) => route.fulfill({ json: [] }))
  await page.route('**/api/v1/benefits', (route) => route.fulfill({ json: [
    { benefitId: 'coupon-search', version: 1, name: '搜索一致性权益', status: 'ACTIVE', createdAt: '2026-10-18T16:30:00Z', resourceKey: '', policy: {} },
  ] }))
  await page.goto('/assets')
  await page.getByRole('tab', { name: '权益与券' }).click()
  const search = page.getByRole('searchbox', { name: '搜索权益' })
  for (const query of ['coupon-search', '已生效', '2026/10/19']) {
    await search.fill(query)
    await expect(page.getByRole('button', { name: '查看搜索一致性权益' })).toBeVisible()
  }
  await expect(search).toHaveAccessibleDescription(/创建时间、状态/)
})
