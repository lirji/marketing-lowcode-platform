import { expect, test } from '@playwright/test'

test('DMN edits, real-contract requests and failure recovery stay usable', async ({ page }, info) => {
  await page.addInitScript(() => {
    window.__MARKETING_CONFIG__ = { API_BASE_URL: '', DEMO_MODE: false, AUTH_MODE: 'DEV', ALLOW_DEV_AUTH: true }
  })
  await page.route('**/api/v1/**', (route) => route.fulfill({ json: [] }))
  await page.route('**/api/v1/client-errors', (route) => route.fulfill({ status: 204 }))
  let evaluations = 0
  await page.route('**/api/v1/dmn/analyze', async (route) => {
    const { table } = route.request().postDataJSON()
    expect(table.inputs).toEqual([{ name: 'amount', type: 'number' }])
    expect(table.rules[0]).toEqual({ inputs: ['>= 100'], outputs: ['"VIP"'] })
    await route.fulfill({ json: { valid: true, gaps: ['Gap: amount < 100'], overlaps: [], messages: [] } })
  })
  await page.route('**/api/v1/dmn/evaluate', async (route) => {
    const { context } = route.request().postDataJSON()
    expect(context).toEqual({ amount: '200' })
    evaluations++
    if (evaluations === 1) await route.fulfill({ status: 503, json: { type: 'about:blank', status: 503, title: 'Busy', detail: '引擎繁忙，请稍后重试', code: 'DMN_WORKBENCH_BUSY' } })
    else await route.fulfill({ json: { success: true, results: { amount: '200', DmnWorkbenchDecision: 'VIP' }, messages: [] } })
  })
  await page.goto('/designers/dmn')
  await expect(page.getByRole('heading', { name: 'DMN 决策表' })).toBeVisible()
  await page.getByLabel('输入字段 1 名称').fill('amount')
  await page.getByLabel('输出字段 1 名称').fill('level')
  await page.getByLabel('规则 1 输入 1').fill('>= 100')
  await page.getByLabel('规则 1 输出 1').fill('"VIP"')
  await page.getByRole('button', { name: '分析表格', exact: true }).click()
  await expect(page.getByText('Gap: amount < 100', { exact: true })).toBeVisible()
  await page.getByLabel('测试输入 1').fill('200')
  await page.getByRole('button', { name: '运行测试行' }).click()
  await expect(page.getByText('引擎繁忙，请稍后重试', { exact: true })).toBeVisible()
  await expect(page.getByLabel('规则 1 输出 1')).toHaveValue('"VIP"')
  await page.screenshot({ path: info.outputPath('dmn-error.png'), fullPage: true })
  await page.getByRole('button', { name: '运行测试行' }).click()
  await expect(page.getByRole('table', { name: '引擎返回值', exact: true }).getByRole('cell', { name: '"VIP"', exact: true })).toBeVisible()
  await expect(page.getByText('引擎求值完成', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  await page.screenshot({ path: info.outputPath('dmn-result.png'), fullPage: true })
  await page.getByRole('button', { name: '新增输入字段' }).click()
  await page.getByLabel('输入字段 2 类型').click()
  await page.getByRole('option', { name: '布尔', exact: true }).click()
  await expect(page.getByLabel('输入字段 2 类型')).toHaveText('布尔')
  await page.getByLabel('输入字段 2 名称').fill('eligible')
  await page.getByLabel('规则 1 输入 2').fill('true')
  await expect(page.getByText('尚未求值', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '删除输入字段 2' }).click()
  await expect(page.getByLabel('规则 1 输入 2')).toHaveCount(0)
  await page.getByRole('button', { name: '新增规则行' }).click()
  await page.getByRole('button', { name: '新增规则行' }).click()
  await page.getByRole('button', { name: '下移规则 1' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button', { name: '下移规则 2' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('规则 3 输入 1')).toHaveValue('>= 100')
  await page.screenshot({ path: info.outputPath('dmn-edited.png'), fullPage: true })
})
